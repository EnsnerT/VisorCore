/** 
 * 
 * @implements {NodeDrawer.NodeRenderer} 
 */
class SimpleBoxRenderer {
    storedProps={};
    /** @type {HTMLImageElement} */
    img=undefined;
    imgLoaded = false;
    
    constructor(){
        this.img = new Image();
        const self = this;
        this.img.onload = function(){
            self.imgLoaded = true;
            self.rerender();
        }
        this.img.src = "map.png";
    }

    callbacks=[];
    add(callback){
        this.callbacks.push(callback);
    }

    evalCollision(node){
        return new NodeDrawer.Collisions2D.Box(node.x,node.y,node.w,node.h);
    }

    /** 
     * @override 
     * @param {NodeDrawer.NodeDrawingContainer<Contexts>} context 
     */
    render(node,context){
        if (!(node.nodeID in this.storedProps)) {
            this.storedProps[node.nodeID] = {
                colorIdx: 1.33
                // color: `hsl(${this.mapRange(Math.hypot(node.x,node.y),0,600,0, 240)},50%,50%)`
            };
        }
        const node_property = this.storedProps[node.nodeID];
        if (node_property.color == undefined){
            if (node_property.colorIdx > 1.1){
                node_property.color = "white";
            } else {
                node_property.color = `hsl(${this.mapRange(node_property.colorIdx, 0, 1, 0, 240)},50%,50%)`;
            }
        }

        const ctx = context.context();
        if ("fill" in ctx) {
            ctx.beginPath();
            
            ctx.fillStyle = node_property.color;
            const start = context.getPositionInWorld({ x: node.x, y: node.y });
            const end = context.getPositionInWorld({ x: node.x, y: node.y }, { x: node.w, y: node.h });
            
            ctx.fillRect(Math.floor(start.x), Math.floor(start.y), Math.ceil(end.x - start.x), Math.ceil(end.y - start.y));
            
            const boundingBox = context.mapOntoNode(node).round();
            if (context.getCurrentViewport().getWorldSpace().scale < .005)
                ctx.imageSmoothingEnabled = false;
            else 
                ctx.imageSmoothingEnabled = true;
            ctx.drawImage(this.img,boundingBox.x,boundingBox.y,boundingBox.mx-boundingBox.x,boundingBox.my-boundingBox.y);
        }
    }
        
    mapRange(valueA, minA, maxA, minB, maxB) {
        return minB + ((valueA - minA) * (maxB - minB)) / (maxA - minA);
    }
    mapRandom(minB, maxB) {
        return this.mapRange(Math.random(), 0, 1, minB, maxB);
    }
    mapRandomRange(range) {
        return this.mapRandom(range[0], range[1]);
    }
    // getRandomDirection(length) {
    // 	const angle = Math.random() * Math.PI * 2;
    // 	return [Math.cos(angle) * length, Math.sin(angle) * length];
    // }
    rerender(){
        this.callbacks.forEach(function(e){return e();});
    }
}

